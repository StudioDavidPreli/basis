// Generates styles/presets.css from the cadence-tokens package
// (decisions/2026-10-05-presets-for-the-embeds.md). Each preset's own
// cadence.css, with `:root` rewritten to `:root[data-preset="<id>"]`, so the
// embeds can switch preset by attribute and no value is ever typed in Basis.
// styles/presets.test.ts fails if the committed file drifts from this output.
//
//   node scripts/presets-css.mjs          write the file
//   import { generate } from it           the expected text, for the test

import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

export const PRESETS = ['standard', 'snappy', 'cinematic']

const require = createRequire(import.meta.url)
// ./dist/* is the subpath the package exports (contracts/cadence-basis.md).
const pkg = path.resolve(path.dirname(require.resolve('cadence-tokens/dist/standard/cadence.css')), '../..')

export function generate() {
  const parts = PRESETS.map(id => {
    const css = readFileSync(path.join(pkg, 'dist', id, 'cadence.css'), 'utf8')
    return `/* ── ${id} ── */\n${css.replaceAll(':root', `:root[data-preset='${id}']`).trim()}\n`
  })
  return `/* GENERATED by scripts/presets-css.mjs from cadence-tokens. Do not edit.
   Every value is Cadence's own; only the selector is Basis's. */\n\n${parts.join('\n')}`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../styles/presets.css')
  writeFileSync(out, generate())
  console.log(`wrote ${path.relative(process.cwd(), out)}`)
}
